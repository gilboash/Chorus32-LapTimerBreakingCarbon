#!/usr/bin/env python3
"""Stamp the firmware version into both the binary and the filesystem image.

The firmware and the web UI ship as two separate OTA uploads, so a timer can
easily end up running one release's firmware with another release's web pages.
To make that detectable we write the same version string into both: the binary
gets it as FIRMWARE_VERSION from src/Version.h, and the filesystem gets a
generated data_src/version.json. The /version endpoint reports both and the UI
warns when they disagree.

This must run before prepare_data.py, which copies data_src into data.
"""

import json
import os
import re
import subprocess
from datetime import datetime, timezone

SCRIPT_DIR = os.getcwd()

VERSION_HEADER = "{}/src/Version.h".format(SCRIPT_DIR)
VERSION_JSON = "{}/data_src/version.json".format(SCRIPT_DIR)
BUILD_INFO_HEADER = "{}/src/BuildInfo.h".format(SCRIPT_DIR)


def read_firmware_version():
    """Pull FIRMWARE_VERSION out of Version.h so it is defined in exactly one place."""
    with open(VERSION_HEADER) as header:
        match = re.search(r'#define\s+FIRMWARE_VERSION\s+"([^"]+)"', header.read())
    if match is None:
        raise RuntimeError("FIRMWARE_VERSION not found in {}".format(VERSION_HEADER))
    return match.group(1)


def read_git_hash():
    """Short commit hash, with a -dirty suffix if the tree has uncommitted changes."""
    try:
        git_hash = subprocess.check_output(
            ["git", "rev-parse", "--short", "HEAD"],
            cwd=SCRIPT_DIR, stderr=subprocess.DEVNULL).decode().strip()
        changed = subprocess.check_output(
            ["git", "status", "--porcelain", "--untracked-files=no"],
            cwd=SCRIPT_DIR, stderr=subprocess.DEVNULL).decode().strip()
        return git_hash + ("-dirty" if changed else "")
    except (subprocess.CalledProcessError, OSError):
        return "unknown"


def write_version_json(version, git_hash, build_date):
    with open(VERSION_JSON, "w") as out:
        json.dump({
            "version": version,
            "git": git_hash,
            "built": build_date,
        }, out)
        out.write("\n")


def write_build_info(git_hash, build_date):
    """Generate the header the firmware picks the build stamp up from.

    Done as a generated header rather than injected -D flags: extra_scripts run
    before projenv exists, so env.Append(CPPDEFINES=...) here never reaches the
    files under src/ and the firmware silently falls back to "unknown".

    Only rewrite when the contents actually change, so repeated builds within
    the same minute don't needlessly recompile everything that includes it.
    """
    contents = (
        "// Generated by version_build.py on every build - do not edit.\n"
        "#ifndef __BUILD_INFO_H__\n"
        "#define __BUILD_INFO_H__\n"
        "\n"
        '#define GIT_HASH "{}"\n'
        '#define BUILD_DATE "{}"\n'
        "\n"
        "#endif // __BUILD_INFO_H__\n"
    ).format(git_hash, build_date)

    if os.path.exists(BUILD_INFO_HEADER):
        with open(BUILD_INFO_HEADER) as existing:
            if existing.read() == contents:
                return

    with open(BUILD_INFO_HEADER, "w") as out:
        out.write(contents)


if __name__ == "__main__" or __name__ == "SCons.Script":
    version = read_firmware_version()
    git_hash = read_git_hash()
    build_date = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M")

    write_version_json(version, git_hash, build_date)
    write_build_info(git_hash, build_date)
    print("Version {} ({}) built {}".format(version, git_hash, build_date))
